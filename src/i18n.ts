const STRINGS: Record<Lang, Record<StringKey, string>> = { en, es, zh, ar };

export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}) {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export type T = (key: StringKey, vars?: Record<string, string | number>) => string;
